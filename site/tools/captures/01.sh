# Example 01 captures. cwd = site/data/01, $BIN = ReleaseSafe build of examples/01-seeded-randomness.
"$BIN" sweep 10000 > sweep.txt 2>&1 || true
"$BIN" sweep 10000 --bug > sweep-bug.txt 2>&1 || true
"$BIN" sweep 10000 --bug --uniform > sweep-bug-uniform.txt 2>&1 || true
"$BIN" run 0 --bug > run0-bug-a.txt 2>&1 || true
"$BIN" run 0 --bug > run0-bug-b.txt 2>&1 || true
"$BIN" run 0 > run0.txt 2>&1 || true
"$BIN" run 0 --bug --dump > run0-bug-dump.txt 2>&1 || true
"$BIN" run 0 --dump > run0-dump.txt 2>&1 || true
# Every generated (a, b) pair of a passing sweep: seed step roll_a a roll_b b  (roll 100 = uniform).
"$BIN" sweep 400 --dump 2>&1 | awk '/dump/ { for (i = 2; i <= 9; i++) { split($i, kv, "="); v[i] = kv[2] }; print v[2], v[3], v[4], v[5], v[6], v[7] }' > pairs-biased.tsv || true
"$BIN" sweep 400 --dump --uniform 2>&1 | awk '/dump/ { for (i = 2; i <= 9; i++) { split($i, kv, "="); v[i] = kv[2] }; print v[2], v[3], v[4], v[5], v[6], v[7] }' > pairs-uniform.tsv || true
# Bucket roll histogram over every value generated by 20000 seeds: roll count
"$BIN" sweep 20000 --dump 2>&1 | awk '/dump/ { split($4, x, "="); split($6, y, "="); n[x[2]]++; n[y[2]]++ } END { for (r = 0; r < 100; r++) print r, n[r] + 0 }' > rolls.tsv || true
# Per seed, with the bug: seed biased_result biased_steps uniform_result uniform_steps
for s in $(seq 0 999); do
  b=$("$BIN" run "$s" --bug 2>&1 | tail -1 || true)
  u=$("$BIN" run "$s" --bug --uniform 2>&1 | tail -1 || true)
  echo "$s $(echo "$b" | awk '{ print $4, $2 }') $(echo "$u" | awk '{ print $4, $2 }')" | sed 's/steps=//g'
done > per-seed.tsv
